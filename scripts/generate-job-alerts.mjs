#!/usr/bin/env node
/**
 * Writes the Prometheus staleness rules from `SCHEDULED_JOBS` — 23-doc §4.
 *
 * **Generated, not hand-written.** 20-doc's entire subject is seven jobs that
 * existed and were never invoked, and the failure that kept it invisible was
 * that nothing anywhere held the list of what SHOULD run. A hand-maintained
 * alert file reintroduces exactly that: a job added to the scheduler and not to
 * the rules is unmonitored, and it looks fine, because an alert that does not
 * exist never fires.
 *
 *   node scripts/generate-job-alerts.mjs
 *
 * The output is committed so a Prometheus deployment needs no Node toolchain,
 * and `job-alerts.spec.ts` fails if the committed file has drifted from the
 * source of truth.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

const {
  SCHEDULED_JOBS,
  expectedIntervalMs,
  SCHEDULE_CRON,
  compareAlphabetically,
} = await import(join(ROOT, 'libs/common/dist/main.js'));

/** Twice the interval, matching `STALENESS_FACTOR` in `job-staleness.ts`. */
const STALENESS_FACTOR = 2;

const rules = Object.values(SCHEDULED_JOBS)
  // Sorted so the generated file is a function of the job list alone: without
  // it, reordering the `SCHEDULED_JOBS` declaration would rewrite this artifact
  // and `job-alerts.spec.ts` would fail over a diff that changes no alert.
  //
  // `compareAlphabetically` rather than a bare `.sort()`, which compares UTF-16
  // code units — right for these ASCII job names by luck, and wrong the moment
  // one is not ASCII. The repo's own comparator is already exported from the
  // bundle this script imports.
  .sort(compareAlphabetically)
  .map((job) => {
    const seconds = (expectedIntervalMs(job) / 1000) * STALENESS_FACTOR;

    return `      # cron: ${SCHEDULE_CRON[job]}
      - alert: ScheduledJobStale
        expr: time() - job_last_success_timestamp_seconds{job="${job}"} > ${seconds}
        for: 10m
        labels: { severity: warning }
        annotations:
          summary: '{{ $labels.job }} has not succeeded in over ${seconds}s'
          description: >-
            The job last succeeded at {{ $value | humanizeTimestamp }}. This
            fires for "it broke" and for "the schedule was never wired" alike —
            the two cases that are indistinguishable from outside and equally bad.

      # **A job with NO SERIES at all**, which the gauge exports as ABSENT rather
      # than as zero. Zero would be 1970 and would satisfy the rule above, so
      # without this the never-wired case would look like the broken case; with
      # it, the two alert separately and get different responses.
      - alert: ScheduledJobMissing
        expr: absent(job_last_success_timestamp_seconds{job="${job}"})
        for: 30m
        labels: { severity: critical }
        annotations:
          summary: '${job} has never reported a successful run'
          description: >-
            No heartbeat exists for this job. Either the scheduler was never
            registered, or the owning service has never been scraped.`;
  })
  .join('\n\n');

const output = `# GENERATED by scripts/generate-job-alerts.mjs — do not edit.
#
# Staleness alerting for every job in SCHEDULED_JOBS — 20-doc §4.2 via
# 23-doc §4. Regenerate with:
#
#     npm run build -w @synapsedesk/common && node scripts/generate-job-alerts.mjs
groups:
  - name: synapsedesk-scheduled-jobs
    rules:
${rules}
`;

const target = join(ROOT, 'docker/prometheus/job-alerts.yml');
writeFileSync(target, output);
console.log(`Wrote ${target}`);
