/**
 * Turns `packages/contracts`'s shared vocabulary into Java constants.
 *
 * **Generated, never copied.** Java cannot import TypeScript, and a
 * hand-written list of a few hundred strings is a list that is right on the
 * day it is written. The two implementations compare against the same
 * subjects, the same event names and the same metadata keys; a Java gateway
 * holding a stale `ticket.created` subscribes to nothing and reports no error.
 *
 * **Only VOCABULARY — never behaviour.** A function in `packages/contracts` is
 * reimplemented in Java and pinned by a shared fixture table, because
 * generating logic from one language into another produces code nobody reads
 * and nobody can fix.
 *
 * CommonJS so `scripts/jest.config.ts` can test it: ts-jest leaves `.mjs`
 * untransformed.
 */

/**
 * What is exported, grouped one Java class per group.
 *
 * A declared registry rather than "every export", because `packages/contracts` has
 * 378 of them and most are types, functions or config the Java side has no
 * use for. The completeness guard below is what stops the registry going
 * stale.
 */
const GROUPS = [
  {
    className: 'Subjects',
    purpose:
      'NATS subjects. A gateway subscribing to a stale one reports no error — it simply receives nothing.',
    exports: [
      'NOTIFICATION_PATTERNS',
      'NOTIFICATION_REALTIME_PATTERNS',
      'AUDIT_PATTERNS',
      'TICKET_PATTERNS',
      'STORAGE_PATTERNS',
      'DOCUMENT_PATTERNS',
      'BILLING_PATTERNS',
      'EMAIL_INBOUND_PATTERNS',
    ],
  },
  {
    className: 'RealtimeEvents',
    purpose:
      'Socket event names, both directions, and the namespace clients connect to. A renamed one is a client that stops receiving, silently.',
    exports: [
      'REALTIME_EVENTS',
      'CLIENT_EVENTS',
      'REALTIME_SOCKET',
      'CONNECTION_REFUSED_CODES',
    ],
  },
  {
    className: 'GrpcMetadata',
    purpose:
      'The caller-context keys every peer reads off the metadata. A missing one is a peer applying the wrong tenant filter.',
    exports: ['GRPC_CONTEXT_METADATA'],
  },
  {
    className: 'PasswordPolicy',
    purpose:
      'The rule every password a person sets meets, read by `@StrongPassword`. A stale copy is a gateway and a web checklist that disagree on what a password needs.',
    exports: ['PASSWORD_POLICY'],
  },
  {
    className: 'SessionKeys',
    purpose:
      'The Redis keys auth-service writes and the gateway reads. A stale prefix is a revoked session the gateway never refuses.',
    exports: ['REVOKED_SESSION_KEY_PREFIX'],
  },
];

/** Every `*_PATTERNS` export must be in a group, or named here with a reason. */
const PATTERNS_NOT_EXPORTED = {};

/** `TICKET_PATTERNS` -> `TICKET_PATTERNS`; `foo.bar` -> `FOO_BAR`. */
function constantName(key) {
  return key
    .replace(/([a-z0-9])([A-Z])/gu, '$1_$2')
    .replace(/[.\-/]/gu, '_')
    .toUpperCase();
}

// Code-unit order, as a bare sort() had it: the output is byte-compared.
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0); // NOSONAR

/** The text without its trailing newlines, read without a pattern. */
function trimTrailingNewlines(text) {
  let end = text.length;
  while (end > 0 && text[end - 1] === '\n') end -= 1;
  return text.slice(0, end);
}

function javaString(value) {
  return `"${String(value).replace(/\\/gu, '\\\\').replace(/"/gu, '\\"')}"`;
}

/**
 * One Java file's source, deterministic: keys sorted, so a re-export with no
 * change produces byte-identical output and `--check` means what it says.
 */
function renderClass(group, common) {
  const lines = [];

  for (const exportName of [...group.exports].sort(byCodeUnit)) {
    const value = common[exportName];
    if (value === undefined) {
      throw new Error(
        `${exportName} is not exported by @synapsedesk/contracts`,
      );
    }

    lines.push(`  /** {@code ${exportName}} in \`packages/contracts\`. */`);

    // A plain string is one constant, named as the export is.
    if (typeof value === 'string') {
      lines.push(
        `  public static final String ${exportName} = ${javaString(value)};`,
        '',
      );
      continue;
    }

    for (const key of Object.keys(value).sort(byCodeUnit)) {
      const name = `${constantName(exportName.replace(/_PATTERNS$/u, ''))}_${constantName(key)}`;
      lines.push(
        Number.isInteger(value[key])
          ? `  public static final int ${name} = ${value[key]};`
          : `  public static final String ${name} = ${javaString(value[key])};`,
      );
    }

    lines.push('');
  }

  return `package com.synapsedesk.gateway.common.contracts;

/**
 * ${group.purpose}
 *
 * <p><b>Generated by \`scripts/export-java-contracts.mjs\` from the built
 * \`packages/contracts\` — do not edit.</b> \`npm run java:contracts:check\` fails on
 * drift, so an edit here is reverted by the next export rather than kept.
 */
public final class ${group.className} {

  private ${group.className}() {}

${trimTrailingNewlines(lines.join('\n'))}
}
`;
}

/** The files this generator owns: relative path -> source. */
function renderAll(common) {
  const files = {};

  for (const group of GROUPS) {
    files[`${group.className}.java`] = renderClass(group, common);
  }

  return files;
}

/**
 * Every `*_PATTERNS` export that no group publishes.
 *
 * **Scanned from the LIBRARY toward the registry**, never the reverse: a
 * registry compared against itself agrees forever, and the failure this
 * prevents is a new subject family that Java never learns about. The reverse
 * direction — a group naming an export that no longer exists — is caught by
 * `renderClass` throwing.
 */
function unexportedPatterns(common) {
  const published = new Set(GROUPS.flatMap((group) => group.exports));

  return Object.keys(common)
    .filter((name) => /_PATTERNS$/u.test(name))
    .filter((name) => !published.has(name) && !(name in PATTERNS_NOT_EXPORTED))
    .sort(byCodeUnit);
}

module.exports = {
  GROUPS,
  PATTERNS_NOT_EXPORTED,
  constantName,
  renderAll,
  renderClass,
  unexportedPatterns,
};
