/**
 * @file Writes `src/generated/session-routes.ts`: the operations the published
 * document secures with the access cookie, as method and path pattern.
 *
 * The browser fetcher refreshes on a 401 only for these, because a refresh can
 * only help a call the access cookie authorises. A sign-in leg (no security,
 * or the MFA or refresh cookie) that answers 401 is a wrong password or an
 * expired challenge, and refreshing there would send the user away from the
 * page that can fix it.
 *
 *   node scripts/generate-session-routes.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const DOCUMENT = join(HERE, '../../../docs/reference/openapi.json');
const OUTPUT = join(HERE, '../src/generated/session-routes.ts');

const document = JSON.parse(readFileSync(DOCUMENT, 'utf8'));
const routes = [];

for (const [path, operations] of Object.entries(document.paths)) {
  for (const [method, operation] of Object.entries(operations)) {
    const schemes = (operation.security ?? []).flatMap((entry) =>
      Object.keys(entry),
    );
    if (!schemes.includes('access-cookie')) continue;

    const pattern = path
      .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
      .replace(/\\\{[^/]+?\\\}/g, '[^/]+');
    routes.push([method.toUpperCase(), `^${pattern}$`]);
  }
}

if (routes.length === 0) {
  throw new Error(
    `No access-cookie operation in ${DOCUMENT}: the scan read nothing.`,
  );
}

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(
  OUTPUT,
  '// Generated by scripts/generate-session-routes.mjs from docs/reference/openapi.json. Do not edit.\n' +
    'export const SESSION_ROUTES: readonly (readonly [string, RegExp])[] = [\n' +
    routes
      .map(
        ([method, pattern]) =>
          `  [${JSON.stringify(method)}, new RegExp(${JSON.stringify(pattern)})],`,
      )
      .join('\n') +
    '\n];\n',
);
console.log(`Wrote ${routes.length} session routes to ${OUTPUT}`);
